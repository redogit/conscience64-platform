import assert from 'node:assert/strict';
const scene = await import('./horizon-scene.mjs').catch(() => ({}));
assert.equal(typeof scene.createSceneModel, 'function', 'the horizon must expose a deterministic query scene model');
const { createSceneModel, layoutScene, tokensFor } = scene;
assert.deepEqual(tokensFor('  hello, 世界  hello,\n🌌 '), ['hello,', '世界', 'hello,', '🌌']);
for (const [width, height] of [[1440,900],[390,844],[0,0],[1,1]]) {
  const layout = layoutScene(width,height);
  assert.ok(Object.values(layout).every(Number.isFinite), 'layout must remain finite at every viewport size');
  assert.ok(layout.radius > 0);
  assert.ok(layout.centerX <= layout.width && layout.centerY <= layout.height);
}
const desktop = layoutScene(1440,900);
assert.equal(desktop.centerX,720);
assert.equal(desktop.centerY,324);
assert.equal(desktop.radius,198);
assert.equal(layoutScene(390,844).centerY,253.2);
const model = createSceneModel();
model.setQuery('Ice 世界', 10);
assert.deepEqual(model.words, ['Ice','世界']);
const first = model.sample(10, desktop);
assert.equal(first.trails.length,2);
assert.equal(first.trails[0].progress,0);
model.setQuery('Ice 世界 now', 10.5);
const added = model.sample(10.5,desktop);
assert.ok(added.trails[0].progress > 0, 'existing words keep travelling when another word arrives');
assert.equal(added.trails[2].progress,0);
model.setQuery('Ice 世界 nowhere', 10.7);
assert.equal(model.sample(10.7,desktop).trails[2].word,'nowhere', 'partial words retain exactly what was typed');
assert.ok(model.sample(10.7,desktop).trails[2].progress > 0, 'editing a word must not restart its strand on every keystroke');
assert.deepEqual(model.sample(11,desktop),model.sample(11,desktop), 'geometry is deterministic');
model.setQuery('Ocean 世界 nowhere',11);
assert.equal(model.sample(11,desktop).trails[0].progress,0,'replacing a word detaches a new strand');
assert.ok(model.sample(11,desktop).trails[1].progress>0,'unmodified words keep their existing strands');
const reduced=model.sample(11,desktop,true);
assert.ok(reduced.trails.every(t=>t.progress===1), 'reduced motion presents settled strands');
model.setWordTargets([{x:100,y:200},{x:220,y:200},{x:350,y:200}]);
assert.deepEqual(model.sample(11,desktop).trails[1].end,{x:220,y:200});
model.setQuery(Array.from({length:30},(_,i)=>`word${i}`).join(' '),12);
assert.equal(model.words.length,30);
assert.equal(model.sample(12,desktop).trails.length,12, 'visual work stays bounded without dropping query words');
model.setQuery('',13);
assert.equal(model.sample(13,desktop).trails.length,0);
console.log('PASS exact query words, stable detachment, reduced motion, finite responsive layout and bounded geometry');
