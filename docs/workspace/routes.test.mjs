import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';

const root=new URL('../../conscience64/research/cross-carrier/2026-09-13/internal-update/global_search/',import.meta.url);
const catalog=JSON.parse(await readFile(new URL('catalog.json',root)));
const bundledCatalog=JSON.parse(await readFile(new URL('./public-routes.json',import.meta.url)));
for(const key of ['providers','countries','policy'])assert.deepEqual(bundledCatalog[key],catalog[key],'public route catalogue preserves the original '+key);
assert.equal(bundledCatalog.source.searchSha256,createHash('sha256').update(await readFile(new URL('search.py',root))).digest('hex'));
assert.equal(bundledCatalog.source.catalogSha256,createHash('sha256').update(await readFile(new URL('catalog.json',root))).digest('hex'));
assert.equal(bundledCatalog.capabilities.routeCount,65);
assert.equal(bundledCatalog.countries.length,248);
const query='日本語 🌊 & x=1';
const originalPlan=JSON.parse(execFileSync('python3',[new URL('search.py',root).pathname,query,'--country','GB','--category','research'],{encoding:'utf8'}));
const {createRouteService,planPublicRoutes}=await import('./routes.mjs');
const carrier={searchPath:'preserved/search.py',searchSha256:'search-hash',catalogPath:'preserved/catalog.json',catalogSha256:'catalog-hash',carrier:'preserved-global-search',separateFromCorpus:true};
const catalogue={schema:'orbit.legacy-route-catalogue/v1',providers:catalog.providers,countries:catalog.countries,policy:catalog.policy,source:carrier,capabilities:{routeCount:65,directProviders:['crossref','europepmc'],categories:['all','web','research','code','archives'],countryScope:'keyword hint, not geographic restriction'}};
const plan={...originalPlan,source:carrier};
const calls=[];
const fetchImpl=async(url,options)=>{
 calls.push({url:String(url),options});
 const u=new URL(url);
 const data=u.pathname==='/api/legacy-search'?{...plan,results:[{title:'A research lead',url:'https://doi.org/10.1234/example',doi:'10.1234/example',provider:'crossref',retrieved_at:'2026-09-13T00:00:00Z',provenance:[{provider:'crossref',retrieved_at:'2026-09-13T00:00:00Z'},{provider:'europepmc',retrieved_at:'2026-09-13T00:00:01Z'}],corroborated:true},{title:'unsafe URL',url:'javascript:alert(1)',provider:'crossref'}],provider_runs:[{provider:'crossref',status:'ok',endpoint:'https://api.crossref.org/works',response_sha256:'response-hash'},{provider:'europepmc',status:'unavailable',error:'TimeoutError'}]}:u.searchParams.has('q')?plan:catalogue;
 return {ok:true,json:async()=>structuredClone(data)};
};
const service=createRouteService({baseURL:'http://127.0.0.1:8765',fetchImpl});
assert.equal(calls.length,0,'construction never searches or loads the catalogue');
const found=await service.catalogue();
assert.deepEqual(found.providers,catalog.providers);
assert.deepEqual(found.countries,catalog.countries);
assert.deepEqual(found.policy,catalog.policy);
assert.equal(found.capabilities.routeCount,65);
assert.equal(found.liveRequests,false);
assert.equal(found.corroborated,false);
const planned=await service.plan(query,{country:'gb',category:'research'});
assert.deepEqual(planned.routes,originalPlan.routes,'preserved route rows and query escaping stay exact');
assert.equal(planned.effective_query,originalPlan.effective_query);
assert.equal(planned.country_scope,'keyword hint, not geographic restriction');
assert.equal(planned.relation,'CANDIDATE_ONLY');
const plannedURL=new URL(calls.at(-1).url);
assert.equal(plannedURL.searchParams.get('q'),query);
assert.equal(plannedURL.searchParams.get('country'),'GB');
assert.equal(plannedURL.searchParams.get('category'),'research');
const searched=await service.search(query,{country:'GB',category:'research'});
assert.equal(searched.results.length,1,'unsafe result links are rejected');
const lead=searched.results[0];
assert.equal(lead.id,'doi:10.1234/example');
assert.equal(lead.provider,'Crossref');
assert.equal(lead.providerId,'crossref');
assert.equal(lead.authority,'EXTERNAL_CANDIDATE');
assert.equal(lead.kind,'web');
assert.equal(lead.corroborated,false,'retrieval never corroborates a substantive claim');
assert.equal(lead.provenance.length,2,'both original retrieval traces survive normalization');
assert.equal(lead.provenance[0].responseSha256,'response-hash');
assert.deepEqual(lead.provenance[0].carrier,carrier);
assert.equal(searched.errors[0].provider,'europepmc');
assert.deepEqual(searched.routes,originalPlan.routes);
assert.equal(new URL(calls.at(-1).url).pathname,'/api/legacy-search');
assert.ok(calls.every(call=>new URL(call.url).origin==='http://127.0.0.1:8765'),'only the explicit trusted local backend receives requests');
const publicPlan=planPublicRoutes(query,catalogue,{country:'gb',category:'research'});
assert.deepEqual(publicPlan.routes,originalPlan.routes);
for(const key of ['query','effective_query','country','category','country_scope','unresolved'])assert.deepEqual(publicPlan[key],originalPlan[key]);
assert.equal(publicPlan.engine,'on-device');
assert.equal(publicPlan.liveRequests,false);
const specialQuery="Apostrophe's (stars)! + 世界 /";
const specialOriginal=JSON.parse(execFileSync('python3',[new URL('search.py',root).pathname,specialQuery],{encoding:'utf8'}));
assert.deepEqual(planPublicRoutes(specialQuery,catalogue).routes,specialOriginal.routes,'native and site-search form encodings match the original Python planner');
assert.equal(planPublicRoutes('research',catalogue).routes.length,65);
assert.throws(()=>planPublicRoutes(query,catalogue,{country:'RU'}),/excluded|unknown/i);
assert.throws(()=>planPublicRoutes(query,catalogue,{country:'ZZ'}),/excluded|unknown/i);
const originalLocation=globalThis.location;
globalThis.location={href:'https://example.org/workspace/index.html',origin:'https://example.org'};
const publicCalls=[];
const publicService=createRouteService({catalogueURL:'./public-routes.json',fetchImpl:async url=>{publicCalls.push(String(url));return{ok:true,json:async()=>catalogue};}});
assert.equal(publicCalls.length,0);
assert.deepEqual((await publicService.catalogue()).countries,catalog.countries);
assert.deepEqual((await publicService.plan(query,{country:'GB',category:'research'})).routes,originalPlan.routes);
await assert.rejects(publicService.search(query),/local|loopback|trusted/i);
assert.ok(publicCalls.every(url=>url==='https://example.org/workspace/public-routes.json'),'the public fallback fetches only its explicit same-origin catalogue');
assert.throws(()=>createRouteService({catalogueURL:'https://other.example.org/public-routes.json'}),/same-origin/i);
assert.throws(()=>createRouteService({catalogueURL:'javascript:alert(1)'}),/same-origin/i);
if(originalLocation===undefined)delete globalThis.location;else globalThis.location=originalLocation;
for(const baseURL of [undefined,'https://example.org','http://127.0.0.1.example.org','http://user:password@localhost','file:///tmp/index.html','http://0.0.0.0:8765'])assert.throws(()=>createRouteService({baseURL,fetchImpl}),/local|loopback|trusted/i);
assert.equal(createRouteService({baseURL:'http://[::1]:8765',fetchImpl}).baseURL,'http://[::1]:8765');
const beforeInvalid=calls.length;
await assert.rejects(service.plan('',{}),/query/i);
await assert.rejects(service.plan('x'.repeat(2049),{}),/query/i);
await assert.rejects(service.plan(query,{category:'unknown'}),/category/i);
assert.equal(calls.length,beforeInvalid,'invalid request parameters never leave the browser');
const cancelled=new AbortController();cancelled.abort();
await assert.rejects(service.plan(query,{signal:cancelled.signal}),{name:'AbortError'});
assert.equal(calls.length,beforeInvalid,'pre-aborted calls never fetch');
const held=createRouteService({baseURL:'http://localhost:8765',timeoutMs:20,fetchImpl:()=>new Promise(()=>{})});
await assert.rejects(held.catalogue(),{name:'TimeoutError'});
const aborting=new AbortController();
const pending=held.search(query,{signal:aborting.signal,timeoutMs:1000});
aborting.abort();await assert.rejects(pending,{name:'AbortError'});
const failed=createRouteService({baseURL:'http://localhost:8765',fetchImpl:async()=>({ok:false,status:503,json:async()=>({error:'unavailable'})})});
await assert.rejects(failed.catalogue(),/503/);
console.log('PASS exact preserved route catalogue and plan, local-only transport, bounded timeout, cancellation, candidate provenance and legacy metadata normalization');
